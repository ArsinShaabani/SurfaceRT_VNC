#!/usr/bin/env python3
"""Generates the "*.g.cs" partial classes that the XAML compiler would normally produce.

The Windows 8.1 XAML build generates a partial class for every Page/Application, containing one
field per `x:Name` plus `InitializeComponent()`.  Without them the code-behind cannot be compiled
outside Windows, which is exactly what `tests/SurfaceVnc.StoreCompile` needs to do.

Usage:  python3 tools/generate-xaml-fields.py
Writes: tests/SurfaceVnc.StoreCompile/Generated/*.g.cs  (derived files, not committed)
"""
import os
import re
import sys
import xml.etree.ElementTree as ElementTree

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
STORE_DIR = os.path.join(ROOT, "src", "SurfaceVnc.Store")
OUT_DIR = os.path.join(ROOT, "tests", "SurfaceVnc.StoreCompile", "Generated")

XAML_NAMESPACE = "http://schemas.microsoft.com/winfx/2006/xaml"
CONTROLS_NAMESPACE = "Windows.UI.Xaml.Controls"


def local_name(tag):
    return tag.split("}")[-1]


def generate(xaml_path):
    tree = ElementTree.parse(xaml_path)
    root = tree.getroot()

    class_attribute = root.attrib.get("{%s}Class" % XAML_NAMESPACE)
    if not class_attribute:
        print("skipping {0}: no x:Class".format(os.path.basename(xaml_path)))
        return None

    namespace, class_name = class_attribute.rsplit(".", 1)
    base_tag = local_name(root.tag)
    base_type = "{0}.{1}".format(CONTROLS_NAMESPACE, base_tag)
    if base_tag == "Application":
        base_type = "Windows.UI.Xaml.Application"

    lines = []
    lines.append("// <auto-generated>")
    lines.append("//     Generated by tools/generate-xaml-fields.py from {0}.".format(
        os.path.relpath(xaml_path, ROOT).replace("\\", "/")))
    lines.append("//     This mirrors what the Windows 8.1 XAML compiler emits, so that the")
    lines.append("//     code-behind can be compiled (and therefore type checked) on any platform.")
    lines.append("// </auto-generated>")
    lines.append("")
    lines.append("namespace {0}".format(namespace))
    lines.append("{")
    lines.append("    public sealed partial class {0} : {1}".format(class_name, base_type))
    lines.append("    {")

    for element in root.iter():
        name = element.attrib.get("{%s}Name" % XAML_NAMESPACE)
        if not name:
            continue
        element_type = "{0}.{1}".format(CONTROLS_NAMESPACE, local_name(element.tag))
        lines.append("        internal {0} {1};".format(element_type, name))

    lines.append("")
    lines.append("        private void InitializeComponent()")
    lines.append("        {")
    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    return class_name, "\n".join(lines)


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    generated = 0

    for name in ("MainPage.xaml", "App.xaml"):
        xaml_path = os.path.join(STORE_DIR, name)
        if not os.path.exists(xaml_path):
            print("missing {0}".format(xaml_path), file=sys.stderr)
            return 1

        result = generate(xaml_path)
        if result is None:
            continue

        class_name, text = result
        target = os.path.join(OUT_DIR, class_name + ".g.cs")
        with open(target, "w", encoding="utf-8") as handle:
            handle.write(text)
        print("wrote {0}".format(os.path.relpath(target, ROOT).replace("\\", "/")))
        generated += 1

    if generated == 0:
        print("nothing was generated", file=sys.stderr)
        return 1

    return 0


if __name__ == "__main__":
    sys.exit(main())
